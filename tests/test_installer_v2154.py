"""v2.15.4 安装 / 卸载脚本静态检查（不需要 NSIS）+ 程序内卸载入口。"""
import os, re, tempfile
BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rd = lambda n: open(os.path.join(BASE, n), encoding="utf-8").read()
nsi, off, src, si = rd("RealtimeTranslate_Setup.nsi"), rd("RealtimeTranslate_Setup_Offline.nsi"), rd("desktop_translator.py"), rd("single_instance.py")
mutex = re.search(r'DEFAULT_MUTEX_NAME = "([^"]+)"', si).group(1)
ver = re.search(r'__version__ = "([^"]+)"', src).group(1)
run_value = re.search(r'RUN_VALUE = "([^"]+)"', src).group(1)
res = []
def ok(n, c): print(("PASS " if c else "FAIL ") + n); res.append(bool(c))
ok("mutex matches app", '"%s"' % mutex in nsi)
ok("version matches app", '!define APP_VERSION "%s"' % ver in nsi)
ok("autostart value matches app toggle", '!define APP_ID "%s"' % run_value in nsi and 'WriteRegStr HKCU "${RUN_KEY}" "${APP_ID}"' in nsi)
ok("components page", "MUI_PAGE_COMPONENTS" in nsi)
ok("sections balanced", len(re.findall(r"^Section\b", nsi, re.M)) == nsi.count("SectionEnd"))
ok("functions balanced", len(re.findall(r"^Function\b", nsi, re.M)) == nsi.count("FunctionEnd"))
ok("every MessageBox has silent default", all("/SD" in l for l in nsi.splitlines() if "MessageBox" in l))
ok("silent uninstall keeps data", "/SD IDNO IDNO done" in nsi)
up = nsi.split('Section "-关闭正在运行的程序"')[1].split("SectionEnd")[0]
up = "\n".join(l.split(";")[0] for l in up.splitlines())          # 去掉注释
ok("upgrade never runs old uninstaller", "ExecWait" not in up and "APPDATA" not in up)
ok("uninstall does not rm -r install dir", 'RMDir "$INSTDIR"' in nsi and 'RMDir /r "$INSTDIR"' not in nsi)
ok("KEEPDATA / DELDATA switches", "/KEEPDATA" in nsi and "/DELDATA" in nsi)
ok("Apps & Features fields", all(k in nsi for k in ("InstallLocation", "QuietUninstallString", "EstimatedSize")))
ok("offline wrapper includes main", "!define OFFLINE" in off and '!include "RealtimeTranslate_Setup.nsi"' in off)
ok("offline is 64-bit", "$PROGRAMFILES64" in nsi and "SetRegView 64" in nsi)
ok("app has uninstall button", "卸载程序…" in src and "def find_uninstaller" in src)
ns = {"os": os, "FROZEN": True, "sys": None}
exec(src[src.index("def find_uninstaller"):src.index("def install_info_text")], ns)
tmp = tempfile.mkdtemp()
ok("no uninstaller -> None", ns["find_uninstaller"](tmp) is None)
open(os.path.join(tmp, "Uninstall.exe"), "w").close()
ok("finds Uninstall.exe", ns["find_uninstaller"](tmp).endswith("Uninstall.exe"))
iss = rd("installer.iss")
ok("iss version matches app", '#define MyAppVersion "%s"' % ver in iss)
ok("iss mutex matches app", "AppMutex=%s" % mutex in iss)
ok("iss pascal begin/end balanced", len(re.findall(r"\bbegin\b", iss)) == len(re.findall(r"\bend;", iss)))
ok("iss DELDATA / KEEPDATA", "HasSwitch('/DELDATA')" in iss and "HasSwitch('/KEEPDATA')" in iss)
ok("iss silent uninstall keeps data", iss.index("if UninstallSilent then") < iss.index("MsgBox(Msg"))
ok("iss upgrade never touches user data", "userappdata" not in iss.split("[InstallDelete]")[1].split("[Icons]")[0])
ok("iss autostart value matches app", 'ValueName: "%s"' % run_value in iss)
assert all(res)
